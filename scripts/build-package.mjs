#!/usr/bin/env node
// Builds the installable package ad-design-kit into dist-package/.
//
//   node scripts/build-package.mjs           write src/index.ts, then build JS, types and CSS
//   node scripts/build-package.mjs --check   only check that src/index.ts exports every component (used by npm run check)
//
// Entry points:
//   ad-design-kit              every component in src/components/ui, cn(), setTheme()/loadTheme()
//   ad-design-kit/icons        the 447 Figma icons + createIcon
//   ad-design-kit/styles.css   the tokens + an @source so the app's Tailwind finds the components' classes
// The package ships plain ESM, one file per module, so an app only bundles the components and icons it imports.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
process.chdir(root);
const OUT = 'dist-package';

// ---- src/index.ts: one export line per component file ----------------------------------------------------------
const ui = fs.readdirSync('src/components/ui').filter((f) => f.endsWith('.tsx') && !f.includes('.stories.')).sort();
const index = [
  '// GENERATED by scripts/build-package.mjs — the package entry point. Do not edit by hand: add a component to',
  '// src/components/ui and run `npm run build:package` (npm run check fails while this file is stale).',
  ...ui.map((f) => `export * from './components/ui/${f.replace(/\.tsx$/, '')}';`),
  "export { cn } from './lib/cn';",
  "export { setTheme, loadTheme, themes, type ADDesignKitTheme } from './lib/theme';",
  '',
].join('\n');
const stale = !fs.existsSync('src/index.ts') || fs.readFileSync('src/index.ts', 'utf8') !== index;
// The package version is the design system version (the newest changelog entry; changelog:release sets both).
const pkgVersion = JSON.parse(fs.readFileSync('package.json', 'utf8')).version;
const dsVersion = JSON.parse(fs.readFileSync('.claude/skills/ad-design-kit-design-system/references/changelog.json', 'utf8')).versions[0].version;
if (process.argv.includes('--check')) {
  const problems = [];
  if (stale) problems.push('src/index.ts does not export every component: run `npm run build:package`.');
  if (pkgVersion !== dsVersion) problems.push(`package.json version ${pkgVersion} is not the design system version ${dsVersion}: set it to ${dsVersion}.`);
  if (problems.length) { for (const p of problems) console.error(p); process.exit(1); }
  console.log(`Package ${pkgVersion}: ${ui.length} component files · up to date`);
  process.exit(0);
}
if (stale) fs.writeFileSync('src/index.ts', index);

// ---- JS (vite library mode) and type declarations -------------------------------------------------------------
fs.rmSync(OUT, { recursive: true, force: true });
const run = (cmd, args) => execFileSync(cmd, args, { stdio: 'inherit' });
run('npx', ['vite', 'build', '--config', 'vite.package.config.ts']);
run('npx', ['tsc', '-p', 'tsconfig.package.json']);

// ---- CSS ---------------------------------------------------------------------------------------------------------
// tokens.css is the generated Tailwind theme the app uses; styles.css adds the @source that makes the consuming
// app's Tailwind scan this package's compiled components for the classes they use.
fs.copyFileSync('src/styles/ad-design-kit.css', `${OUT}/tokens.css`);
fs.writeFileSync(
  `${OUT}/styles.css`,
  [
    '/* AD Design Kit for Tailwind CSS v4. In the app stylesheet:',
    '     @import "tailwindcss";',
    '     @import "ad-design-kit/styles.css";',
    '   Theme: <html data-theme="modern|enterprise"> plus class="dark" for dark mode. */',
    '@import "./tokens.css";',
    '@source "./";',
    '',
  ].join('\n'),
);

const count = (dir) => fs.readdirSync(dir, { recursive: true }).filter((f) => String(f).endsWith('.js')).length;
console.log(`Built ${OUT}/: ${count(OUT)} modules, types, styles.css and tokens.css (${ui.length} component files).`);
